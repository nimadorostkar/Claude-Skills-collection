#!/usr/bin/env python3
"""Generate the indexes from the skills themselves, so they cannot drift.

Writes:
    docs/catalog.md                  every skill, by category
    categories/<category>.md         one index per category
    .claude-plugin/marketplace.json  one Claude Code plugin per category

    python scripts/build_index.py           # regenerate
    python scripts/build_index.py --check   # exit non-zero if anything is stale

Never edit the generated files by hand. Change the skill, or the category
metadata below, and re-run this.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
REPO = "nimadorostkar/Claude-Skills-collection"
MARKETPLACE = "claude-skills"

# The single source of truth for categories: directory -> (title, summary).
# Order here is the order of the catalog. validate.py imports this.
CATEGORIES: dict[str, tuple[str, str]] = {
    "languages": ("Languages", "Idiomatic, modern practice for each language, with the quality gate that keeps it honest."),
    "development": ("Development", "The craft that is independent of language: review, debugging, refactoring, design, and version control."),
    "backend": ("Backend", "APIs, services, messaging, and the frameworks that carry them."),
    "frontend": ("Frontend", "Frameworks, architecture, accessibility, and performance in the browser."),
    "mobile": ("Mobile", "Native and cross-platform mobile development, and shipping it safely."),
    "devops": ("DevOps & Cloud", "Infrastructure, delivery, reliability, and the arithmetic of running things in production."),
    "data": ("Data", "Databases, schema design, and the pipelines that move data around."),
    "security": ("Security", "Writing secure code, auditing it, and protecting the supply chain around it."),
    "testing": ("Testing", "What to test, at which level, and how to keep a suite worth running."),
    "ai": ("AI & LLM", "Prompting, retrieval, evaluation, agents, and the production concerns of shipping a model."),
    "agent-tooling": ("Agent Tooling", "Building the skills, hooks, commands, and plugins that agents run on."),
    "finance": ("Finance", "Position sizing, risk, market analysis, and quantitative method. Educational, not advice."),
    "documents": ("Documents", "Producing and parsing Word, Excel, PowerPoint, PDF, and diagrams."),
    "design": ("Design", "Visual design, brand systems, theming, and interface critique."),
    "writing": ("Writing", "Documentation, changelogs, internal communication, and editing."),
    "productivity": ("Productivity", "Research, verification, notes, files, and getting data out of the web."),
    "business": ("Business", "Competitive analysis, product metrics, user research, and go-to-market work."),
}

SUMMARY_MAX = 110

NAME_RE = re.compile(r"^name:\s*(\S+)\s*$", re.M)
DESC_RE = re.compile(r"^description:\s*(.+?)(?=^\w+:)", re.M | re.S)
TITLE_RE = re.compile(r"^# (.+)$", re.M)


def summary(description: str) -> str:
    """The first sentence of the description, minus the "Use when" lead-in."""
    first = re.split(r"(?<=\.)\s", description, maxsplit=1)[0].rstrip(".")
    for lead in ("Use when ", "Use for "):
        if first.startswith(lead):
            first = first[len(lead):]
            first = first[0].upper() + first[1:]
            break
    if len(first) > SUMMARY_MAX:
        first = first[:SUMMARY_MAX].rsplit(" ", 1)[0].rstrip(",;—- ") + "…"
    return first


def load() -> dict[str, list[dict]]:
    by_cat: dict[str, list[dict]] = {c: [] for c in CATEGORIES}
    for path in sorted(SKILLS.glob("*/*/SKILL.md")):
        text = path.read_text(encoding="utf-8")
        fm, body = text.split("---", 2)[1:]
        desc = " ".join(DESC_RE.search(fm).group(1).split())
        by_cat.setdefault(path.parent.parent.name, []).append({
            "name": NAME_RE.search(fm).group(1),
            "title": TITLE_RE.search(body).group(1).strip(),
            "summary": summary(desc),
            "path": path.parent.relative_to(ROOT).as_posix(),
        })
    for skills in by_cat.values():
        skills.sort(key=lambda s: s["name"])
    return by_cat


def catalog(by_cat: dict[str, list[dict]]) -> str:
    total = sum(len(s) for s in by_cat.values())
    out = [
        "# Catalog", "",
        f"All {total} skills, by category. Each links to its `SKILL.md`.", "",
        "<!-- Generated by scripts/build_index.py. Do not edit by hand. -->", "",
        "| Category | Skills |", "| --- | --- |",
    ]
    for cat, (title, _) in CATEGORIES.items():
        out.append(f"| [{title}](../categories/{cat}.md) | {len(by_cat[cat])} |")
    for cat, (title, blurb) in CATEGORIES.items():
        out += ["", f"## {title}", "", blurb, "", "| Skill | Purpose |", "| --- | --- |"]
        for s in by_cat[cat]:
            out.append(f"| [`{s['name']}`](../{s['path']}/SKILL.md) | {s['summary']} |")
    return "\n".join(out) + "\n"


def category_page(cat: str, skills: list[dict]) -> str:
    title, blurb = CATEGORIES[cat]
    out = [
        f"# {title}", "", blurb, "",
        f"{len(skills)} skills. Install just this category in Claude Code:", "",
        "```", f"/plugin install {cat} --marketplace {REPO}", "```", "",
        "<!-- Generated by scripts/build_index.py. Do not edit by hand. -->", "",
        "| Skill | Purpose |", "| --- | --- |",
    ]
    for s in skills:
        out.append(f"| [{s['title']}](../{s['path']}/SKILL.md) | {s['summary']} |")
    out += ["", "---", "", "[All categories](../docs/catalog.md) · [README](../README.md)"]
    return "\n".join(out) + "\n"


def marketplace(by_cat: dict[str, list[dict]]) -> str:
    data = {
        "name": MARKETPLACE,
        "owner": {"name": REPO.split("/")[0]},
        "metadata": {
            "description": "Production-grade skills for Claude Code, one plugin per category.",
        },
        "plugins": [
            {
                "name": cat,
                "description": f"{title} — {blurb}",
                "source": "./",
                "strict": False,
                "category": cat,
                "skills": [f"./{s['path']}" for s in by_cat[cat]],
            }
            for cat, (title, blurb) in CATEGORIES.items()
        ],
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def outputs() -> dict[Path, str]:
    by_cat = load()
    unknown = set(by_cat) - set(CATEGORIES)
    if unknown:
        sys.exit(f"error: unknown category directories: {', '.join(sorted(unknown))}")
    files = {ROOT / "docs" / "catalog.md": catalog(by_cat)}
    for cat in CATEGORIES:
        files[ROOT / "categories" / f"{cat}.md"] = category_page(cat, by_cat[cat])
    files[ROOT / ".claude-plugin" / "marketplace.json"] = marketplace(by_cat)
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = parser.parse_args()

    stale = []
    for path, content in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if args.check and stale:
        for p in stale:
            print(f"STALE  {p}", file=sys.stderr)
        print("\nRun `python scripts/build_index.py` and commit the result.", file=sys.stderr)
        return 1

    print(f"{'Updated' if stale else 'Up to date'}: {len(stale)} file(s) changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
